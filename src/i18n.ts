export type Message = keyof typeof messages;
let locale: Locale = "zh";
export function resolveLocale(
  saved: string | null,
  languages: readonly string[],
): Locale {
  if (saved === "zh" || saved === "en") return saved;
  const language = languages.find((value) => /^(zh|en)(-|$)/i.test(value));
  return language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}
export function t(key: Message, values: Record<string, string | number> = {}) {
  const source =
    locale === "en"
      ? messages[key]
      : key === "操作详情"
        ? "A / D 移动 · 空格跳跃 · Ctrl 翻滚<br>鼠标左键轻击 · 右键重击，长按蓄力、松开释放<br>Q 烬线（6 秒） · F 回火（0.8 秒，可被打断）<br>手柄：A 跳跃 · X 轻击 · RT 重击/蓄力 · B / RB 闪避<br>Y 回火 · LB 烬线 · Start 暂停<br>键盘备用：J 轻击 / L 重击"
        : key;
  return source.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

// Capture only authored, translatable text nodes/attributes once. Updating their
// values never replaces buttons, listeners, the canvas, or live game state.
export function initLocalization() {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem("emberfall-language");
  } catch {
    /* Storage may be disabled. */
  }
  locale = resolveLocale(saved, navigator.languages);
  const bindings: (() => void)[] = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const key = node.textContent?.trim().replace(/\s+/g, " ") ?? "";
    if (Object.hasOwn(messages, key)) {
      const prefix = node.textContent?.match(/^\s*/)?.[0] ?? "";
      const suffix = node.textContent?.match(/\s*$/)?.[0] ?? "";
      bindings.push(() => {
        if (node.isConnected)
          node.textContent = prefix + t(key as Message) + suffix;
      });
    }
  }
  for (const element of document.querySelectorAll(
    '[aria-label], meta[name="description"]',
  )) {
    const attr = element instanceof HTMLMetaElement ? "content" : "aria-label";
    const key = element.getAttribute(attr) ?? "";
    if (Object.hasOwn(messages, key))
      bindings.push(() => element.setAttribute(attr, t(key as Message)));
  }
  const apply = () => {
    bindings.forEach((update) => update());
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    document.title = t("余烬 EMBERFALL — 丧钟执刑者");
  };
  apply();
  return {
    locale,
    change(value: Locale) {
      locale = value;
      try {
        localStorage.setItem("emberfall-language", locale);
      } catch {
        /* Session still works. */
      }
      apply();
    },
  };
}
